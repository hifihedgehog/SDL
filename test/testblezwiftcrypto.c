/* MakeKey gives a new key each time, a point on the curve that a device can
   derive from, and a new exchange drops the old session */
static void TestMakeKey(void)
{
    SDL_ZwiftCrypto crypto, other_crypto, device_crypto;
    SDL_ZwiftKeys *keys = NewKeys(&crypto);
    SDL_ZwiftKeys *other = NewKeys(&other_crypto);
    SDL_ZwiftKeys *device = NewKeys(&device_crypto);
    uint8_t first[KEY_SIZE], second[KEY_SIZE], third[KEY_SIZE], hkdf[HKDF_SIZE];

    if (keys && other && device) {
        BH_CHECK(SetPair(device, device_d, device_key), "the device's pair");
        BH_CHECK(MakeKey(&crypto, first), "first MakeKey");
        BH_CHECK(MakeKey(&crypto, second), "second MakeKey");
        BH_CHECK(MakeKey(&other_crypto, third), "another exchange's MakeKey");
        BH_CHECK(!Same(first, second, KEY_SIZE) && !Same(first, third, KEY_SIZE) && !Same(second, third, KEY_SIZE),
                 "every key is new");
        BH_CHECK(Derive(&device_crypto, first) && Derive(&device_crypto, second) && Derive(&device_crypto, third),
                 "every key is a point on the curve");
        BH_CHECK(Derive(&crypto, device_key) && SDL_ZwiftCrypto_GetDerived(keys, hkdf), "the host derives");
        BH_CHECK(!Same(hkdf, session_hkdf, HKDF_SIZE), "with its own key, not the fixed one");
        BH_CHECK(MakeKey(&crypto, first), "a new exchange");
        BH_CHECK(!SDL_ZwiftCrypto_GetDerived(keys, hkdf), "the old session went with it");
        BH_CHECK(!Same(first, second, KEY_SIZE), "a new key again");
        /* A fixed pair stays in place, and a new exchange on it still drops
           the old session */
        BH_CHECK(SetPair(keys, host_d, host_key), "SetKeyPair");
        BH_CHECK(MakeKey(&crypto, first) && Same(first, host_key, KEY_SIZE), "the fixed key");
        BH_CHECK(Derive(&crypto, device_key) && Derived(keys, session_hkdf), "the fixed pair derives");
        BH_CHECK(MakeKey(&crypto, second) && Same(second, host_key, KEY_SIZE), "the fixed key again");
        BH_CHECK(!SDL_ZwiftCrypto_GetDerived(keys, hkdf), "the fixed pair's old session went with it");
    }
    SDL_ZwiftCrypto_Destroy(keys);
    SDL_ZwiftCrypto_Destroy(other);
    SDL_ZwiftCrypto_Destroy(device);
}

/* The index of the last write in the log, -1 when none */
static int LastWrite(const BH_Harness *h)
{
    int i;

    for (i = h->nactions - 1; i >= 0; --i) {
        if (h->actions[i].action.kind == SDL_BLE_ACTION_WRITE) {
            return i;
        }
    }
    return -1;
}

/* A right half of firmware 1.x on the session, run until the key exchange
   is written. NULL when the handshake did not go as the part says. */
static BH_Harness *KeySent(const SDL_ZwiftCrypto *crypto, const uint8_t *key)
{
    BH_Harness *h = BH_Create(&SDL_BLEZwiftFamily, SDL_ZWIFT_PLAY_RIGHT, crypto, false);
    const SDL_BLEAction *action;
    int writes[4];
    int index;

    BH_Start(h, false);
    BH_CHECK(BH_Writes(h, writes, 4) == 1 && BH_IsWrite(h, writes[0], ride_on, sizeof(ride_on)), "RideOn first");
    BH_WriteAll(h);
    /* No ASYNC value within 10 s of the write */
    BH_Advance(h, h->now + SDL_ZWIFT_HANDSHAKE_MS);
    BH_CHECK(BH_Writes(h, writes, 4) == 2, "one more write after 10 s");
    index = LastWrite(h);
    if (index < 0) {
        BH_Destroy(h);
        return NULL;
    }
    action = &h->actions[index].action;
    BH_CHECK(action->characteristic == SDL_ZWIFT_SYNC_RX && action->response, "to SYNC_RX with a response");
    BH_CHECK(action->length == 8 + KEY_SIZE, "RideOn, two bytes and 64 key bytes, %d bytes written", action->length);
    BH_CHECK(Same(action->data, ride_on, sizeof(ride_on)) && action->data[6] == 0x01 && action->data[7] == 0x02,
             "RideOn 01 02");
    BH_CHECK(Same(&action->data[8], key, KEY_SIZE), "the host's key, all 64 bytes");
    if (action->length != 8 + KEY_SIZE) {
        BH_Destroy(h);
        return NULL;
    }
    return h;
}

/* The Zwift module's encrypted handshake end to end: the host's key on the
   wire, the device's answer on SYNC_TX, then encrypted ASYNC frames */
static void Session(const uint8_t *d, const uint8_t *key, const uint8_t *hkdf, const uint8_t *mirror,
                    const uint8_t *pressed, const uint8_t *released)
{
    SDL_ZwiftCrypto crypto, device_crypto;
    SDL_ZwiftKeys *keys = NewKeys(&crypto);
    SDL_ZwiftKeys *device = NewKeys(&device_crypto);
    BH_Harness *h = NULL;
    uint8_t reply[8 + KEY_SIZE], wire[KEY_SIZE], plain[FRAME_SIZE], frame[FRAME_SIZE];
    int snapshots;

    if (keys && device) {
        BH_CHECK(SetPair(keys, d, key), "the host's pair");
        BH_CHECK(SetPair(device, device_d, device_key), "the device's pair");
        h = KeySent(&crypto, key);
    }
    if (h) {
        /* The device's side of the exchange, from the key on the wire. Its
           own SDL_ZwiftKeys salts with its peer's key first. */
        memcpy(wire, &h->actions[LastWrite(h)].action.data[8], KEY_SIZE);
        BH_CHECK(Derive(&device_crypto, wire) && Derived(device, mirror), "the device's view of the secret");

        /* RideOn, two bytes and the device's key, 01 01 as in zwiftplay's capture */
        memcpy(reply, ride_on, sizeof(ride_on));
        reply[6] = 0x01;
        reply[7] = 0x01;
        BH_CHECK(MakeKey(&device_crypto, &reply[8]) && Same(&reply[8], device_key, KEY_SIZE), "the device's key");
        BH_Value(h, SDL_ZWIFT_SYNC_TX, reply, sizeof(reply), false);
        BH_CHECK(Derived(keys, hkdf), "the host derived the independent HKDF output");
        BH_CHECK(!h->published && h->nsnapshots == 0, "nothing published before the first frame");

        /* An encrypted frame from the independent side: A pressed */
        BH_Value(h, SDL_ZWIFT_ASYNC, pressed, FRAME_SIZE, false);
        BH_CHECK(h->published && BH_Count(h, SDL_BLE_ACTION_PUBLISH) == 1, "the session published");
        BH_CHECK(BH_Controls(h)->buttons == EAST_BIT, "EAST only, buttons %08x", (unsigned)BH_Controls(h)->buttons);
        BH_CHECK(BH_Axis(h, SDL_BLE_AXIS_RIGHTX) == 0 && BH_Axis(h, SDL_BLE_AXIS_RIGHT_TRIGGER) == -32768,
                 "RIGHTX 0 and RIGHT_TRIGGER at rest");

        /* A flipped tag bit changes nothing */
        snapshots = h->nsnapshots;
        memcpy(frame, released, FRAME_SIZE);
        frame[FRAME_SIZE - 1] ^= 0x01;
        BH_Value(h, SDL_ZWIFT_ASYNC, frame, FRAME_SIZE, false);
        BH_CHECK(h->nsnapshots == snapshots && BH_Button(h, SDL_BLE_BUTTON_EAST), "a tampered frame was applied");
        /* A plain message after the exchange is not a frame */
        BH_Value(h, SDL_ZWIFT_ASYNC, message_released, MESSAGE_SIZE, false);
        BH_CHECK(h->nsnapshots == snapshots && BH_Button(h, SDL_BLE_BUTTON_EAST), "a plain message was applied");

        /* The next counter releases A */
        BH_Value(h, SDL_ZWIFT_ASYNC, released, FRAME_SIZE, false);
        BH_CHECK(h->nsnapshots == snapshots + 1 && BH_Controls(h)->buttons == 0, "EAST released");
        BH_CHECK(!SDL_BLESession_Ended(&h->session) && BH_Count(h, SDL_BLE_ACTION_BACKOFF) == 0, "the session runs");

        /* The host's decrypt matches the independent side for both frames */
        BH_CHECK(Decrypt(&crypto, pressed, FRAME_SIZE, plain) && Same(plain, message_pressed, MESSAGE_SIZE),
                 "the pressed frame");
        BH_Destroy(h);
    }
    SDL_ZwiftCrypto_Destroy(keys);
    SDL_ZwiftCrypto_Destroy(device);
}

