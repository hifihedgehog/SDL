typedef void (*TestFunction)(void);

/* Runs one block and prints its own check count */
static void Run(const char *label, TestFunction test)
{
    const int checks = bh_checks;
    const int failures = bh_failures;

    test();
    printf("%s: %d checks, %d failures\n", label, bh_checks - checks, bh_failures - failures);
}

static bool Same(const uint8_t *a, const uint8_t *b, size_t length)
{
    return memcmp(a, b, length) == 0;
}

static bool AllZero(const uint8_t *data, size_t length)
{
    size_t i;

    for (i = 0; i < length; ++i) {
        if (data[i] != 0) {
            return false;
        }
    }
    return true;
}

/* An exact-size heap copy. An empty one is malloc(0), a block with no bytes,
   so AddressSanitizer reports a read of its byte 0. It may be NULL. */
static uint8_t *Copy(const uint8_t *data, size_t length)
{
    uint8_t *copy = (uint8_t *)malloc(length);

    if (!copy && length) {
        printf("out of memory\n");
        exit(2);
    }
    if (length) {
        memcpy(copy, data, length);
    }
    return copy;
}

/* A key exchange, or NULL after a failed check when CNG does not load */
static SDL_ZwiftKeys *NewKeys(SDL_ZwiftCrypto *crypto)
{
    SDL_ZwiftKeys *keys = SDL_ZwiftCrypto_Create(crypto);

    BH_CHECK(keys != NULL, "CNG did not load");
    return keys;
}

static bool SetPair(SDL_ZwiftKeys *keys, const uint8_t *d, const uint8_t *key)
{
    return SDL_ZwiftCrypto_SetKeyPair(keys, d, key, &key[32]);
}

/* MakeKey into an exact-size buffer */
static bool MakeKey(const SDL_ZwiftCrypto *crypto, uint8_t *key)
{
    uint8_t *out = (uint8_t *)malloc(KEY_SIZE);
    bool result;

    if (!out) {
        printf("out of memory\n");
        exit(2);
    }
    result = crypto->MakeKey(crypto->userdata, out);
    memcpy(key, out, KEY_SIZE);
    free(out);
    return result;
}

/* Derive from an exact-size copy of the device's key */
static bool Derive(const SDL_ZwiftCrypto *crypto, const uint8_t *key)
{
    uint8_t *copy = Copy(key, KEY_SIZE);
    const bool result = crypto->Derive(crypto->userdata, copy);

    free(copy);
    return result;
}

/* Decrypt from an exact-size copy of the frame into an exact-size buffer.
   out receives length - 8 bytes, or nothing for a frame of 8 bytes or less. */
static bool Decrypt(const SDL_ZwiftCrypto *crypto, const uint8_t *frame, size_t length, uint8_t *out)
{
    const size_t count = (length > SDL_ZWIFT_FRAME_EXTRA) ? length - SDL_ZWIFT_FRAME_EXTRA : 0;
    uint8_t *copy = Copy(frame, length);
    uint8_t *plain = (uint8_t *)malloc(count);
    bool result;

    if (!plain && count) {
        printf("out of memory\n");
        exit(2);
    }
    if (count) {
        memset(plain, 0xA5, count);
    }
    result = crypto->Decrypt(crypto->userdata, copy, length, plain);
    if (count) {
        memcpy(out, plain, count);
    }
    free(plain);
    free(copy);
    return result;
}

static bool Derived(const SDL_ZwiftKeys *keys, const uint8_t *expected)
{
    uint8_t hkdf[HKDF_SIZE];

    return SDL_ZwiftCrypto_GetDerived(keys, hkdf) && Same(hkdf, expected, HKDF_SIZE);
}

/* Create fills the entry points, and nothing works before its step */
static void TestEntryPoints(void)
{
    SDL_ZwiftCrypto crypto;
    SDL_ZwiftKeys *keys;
    uint8_t hkdf[HKDF_SIZE], plain[FRAME_SIZE];

    BH_CHECK(SDL_ZwiftCrypto_Create(NULL) == NULL, "Create without entry points");
    SDL_ZwiftCrypto_Destroy(NULL);
    BH_CHECK(!SDL_ZwiftCrypto_GetDerived(NULL, hkdf), "GetDerived without keys");
    BH_CHECK(!SDL_ZwiftCrypto_SetKeyPair(NULL, host_d, host_key, &host_key[32]), "SetKeyPair without keys");

    memset(&crypto, 0xCC, sizeof(crypto));
    keys = NewKeys(&crypto);
    if (!keys) {
        return;
    }
    BH_CHECK(crypto.userdata == keys && crypto.MakeKey && crypto.Derive && crypto.Decrypt, "entry points");
    BH_CHECK(!SDL_ZwiftCrypto_GetDerived(keys, hkdf), "derived before any Derive");
    BH_CHECK(!Derive(&crypto, device_key), "Derive before a key pair");
    BH_CHECK(!Decrypt(&crypto, frame_pressed, FRAME_SIZE, plain), "Decrypt before Derive");
    SDL_ZwiftCrypto_Destroy(keys);
}

/* Test 14: with fixed private keys for both sides, the HKDF output, key and
   nonce prefix equal the independent values, and the frame that side
   encrypted under counter 01 00 00 00 decrypts to the message of test 1 */
static void Test14_Vectors(void)
{
    SDL_ZwiftCrypto crypto;
    SDL_ZwiftKeys *keys = NewKeys(&crypto);
    uint8_t key[KEY_SIZE], hkdf[HKDF_SIZE], plain[FRAME_SIZE];

    if (!keys) {
        return;
    }
    BH_CHECK(SetPair(keys, host_d, host_key), "SetKeyPair");
    BH_CHECK(MakeKey(&crypto, key) && Same(key, host_key, KEY_SIZE), "the fixed key is the one sent");
    BH_CHECK(!SDL_ZwiftCrypto_GetDerived(keys, hkdf), "derived before Derive");
    BH_CHECK(Derive(&crypto, device_key), "Derive");
    BH_CHECK(SDL_ZwiftCrypto_GetDerived(keys, hkdf), "GetDerived");
    BH_CHECK(Same(hkdf, session_hkdf, HKDF_SIZE), "HKDF output");
    BH_CHECK(Same(hkdf, session_key, sizeof(session_key)), "AES key, bytes 0 to 31");
    BH_CHECK(Same(&hkdf[32], session_prefix, sizeof(session_prefix)), "nonce prefix, bytes 32 to 35");
    BH_CHECK(Decrypt(&crypto, frame_pressed, FRAME_SIZE, plain), "counter 01 00 00 00 decrypts");
    BH_CHECK(Same(plain, message_pressed, MESSAGE_SIZE), "to the message of test 1");
    BH_CHECK(Decrypt(&crypto, frame_released, FRAME_SIZE, plain), "counter 02 00 00 00 decrypts");
    BH_CHECK(Same(plain, message_released, MESSAGE_SIZE), "to the released message");
    /* The same exchange again gives the same session */
    BH_CHECK(Derive(&crypto, device_key) && Derived(keys, session_hkdf), "a second Derive");
    BH_CHECK(Decrypt(&crypto, frame_pressed, FRAME_SIZE, plain) && Same(plain, message_pressed, MESSAGE_SIZE),
             "decrypts after a second Derive");
    SDL_ZwiftCrypto_Destroy(keys);
}

/* Test 14: a flipped tag bit drops the frame. So do a flipped ciphertext bit,
   another counter, a truncated frame and a longer one, and every dropped
   frame leaves plain zeroed. */
static void Test14_Tampering(void)
{
    SDL_ZwiftCrypto crypto;
    SDL_ZwiftKeys *keys = NewKeys(&crypto);
    uint8_t frame[FRAME_SIZE + 1], plain[FRAME_SIZE];
    size_t length, i;
    int bit;

    if (!keys) {
        return;
    }
    BH_CHECK(SetPair(keys, host_d, host_key) && Derive(&crypto, device_key), "exchange");

    /* Every bit of the tag */
    for (i = FRAME_SIZE - 4; i < FRAME_SIZE; ++i) {
        for (bit = 0; bit < 8; ++bit) {
            memcpy(frame, frame_pressed, FRAME_SIZE);
            frame[i] ^= (uint8_t)(1u << bit);
            BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE, plain), "tag byte %d bit %d flipped", (int)i, bit);
            BH_CHECK(AllZero(plain, MESSAGE_SIZE), "tag byte %d bit %d left plain bytes", (int)i, bit);
        }
    }
    /* Every bit of the ciphertext */
    for (i = 4; i < FRAME_SIZE - 4; ++i) {
        for (bit = 0; bit < 8; ++bit) {
            memcpy(frame, frame_pressed, FRAME_SIZE);
            frame[i] ^= (uint8_t)(1u << bit);
            BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE, plain), "ciphertext byte %d bit %d flipped", (int)i, bit);
        }
    }
    /* Every bit of the counter: the nonce takes its bytes as received */
    for (i = 0; i < 4; ++i) {
        for (bit = 0; bit < 8; ++bit) {
            memcpy(frame, frame_pressed, FRAME_SIZE);
            frame[i] ^= (uint8_t)(1u << bit);
            BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE, plain), "counter byte %d bit %d flipped", (int)i, bit);
        }
    }
    /* The counter as a big-endian number */
    memcpy(frame, frame_pressed, FRAME_SIZE);
    frame[0] = 0x00;
    frame[3] = 0x01;
    BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE, plain), "counter 00 00 00 01");
    /* The released frame's ciphertext under the pressed frame's counter */
    memcpy(frame, frame_released, FRAME_SIZE);
    memcpy(frame, frame_pressed, 4);
    BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE, plain), "a ciphertext under another counter");
    /* Every truncation */
    for (length = 0; length < FRAME_SIZE; ++length) {
        BH_CHECK(!Decrypt(&crypto, frame_pressed, length, plain), "truncated to %d bytes", (int)length);
    }
    /* A byte more */
    memcpy(frame, frame_pressed, FRAME_SIZE);
    frame[FRAME_SIZE] = 0x00;
    BH_CHECK(!Decrypt(&crypto, frame, FRAME_SIZE + 1, plain), "a byte more");
    /* Positive control after every dropped frame */
    BH_CHECK(Decrypt(&crypto, frame_pressed, FRAME_SIZE, plain) && Same(plain, message_pressed, MESSAGE_SIZE),
             "the untouched frame");
    SDL_ZwiftCrypto_Destroy(keys);
}

